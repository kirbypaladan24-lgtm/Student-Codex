/**
 * Student Codex theme.
 *
 * @param darkTheme follows the system setting by default.
 * @param dynamicColor opt-in (off by default): Material You wallpaper colors on
 *   Android 12+. Kept off for the MVP so the brand palette stays consistent in
 *   demos and screenshots.
 */
@Composable
fun StudentCodexTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkScheme
        else -> LightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = CodexTypography,
        shapes = CodexShapes,
        content = content,
    )
}
